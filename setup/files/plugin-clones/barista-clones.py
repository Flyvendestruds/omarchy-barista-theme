#!/usr/bin/env python3
"""Regenerate barista.* shell plugin clones from the INSTALLED stock plugins.

Why: a clone is a frozen copy of upstream code. When `omarchy update` ships a
new shell (4.0 -> 4.5 rewrote notifications, the image picker, network, ...)
the old copies keep running against a newer shell and break in quiet ways
(0px margins, an empty theme picker). So clones are never edited by hand:
this script rebuilds each one from the current stock source and re-applies
the barista look as a small set of idempotent rules.

Barista rules (the whole delta vs stock):
  * tnum        tabular figures on every panel text (numbers don't jitter)
  * sentence    sentence-case labels instead of ALL CAPS + letter-spacing
  * card-shadow top-level card opts into the step-10 RectangularShadow
  * osd/notify  edge margins follow barista's per-side gaps (Style.gapTop..)
                with a fallback to the stock scalar if step 10 is missing,
                so a wiped Style.qml degrades to stock spacing, never 0px.
  * nightlight  3000K night temperature

Usage: barista-clones.py apply|revert|check [--plugins-dir DIR] [--only id,..]
  apply   back up current clones, regenerate managed ones in place
  revert  restore the clones saved by the last apply
  check   regenerate into a temp dir and report what would change (no writes)
"""
import argparse, datetime, json, os, pathlib, re, shutil, subprocess, sys, tempfile

HOME = pathlib.Path(os.environ.get("BARISTA_HOME") or os.path.expanduser("~"))
PLUGINS = HOME / ".config/omarchy/plugins"
BACKUPS = HOME / ".local/state/omarchy/barista/plugin-backups"
SHELL = pathlib.Path(os.environ.get("OMARCHY_SHELL_DIR", "/usr/share/omarchy/shell"))

PANEL_STYLE = ["tnum", "sentence"]
# clone id -> (stock id, rules). Clones NOT listed here (barista.reminders,
# barista.weather, barista.keyboard-rgb, third-party plugins) are real
# feature forks maintained by hand and are never touched.
MANAGED = {
    "barista.agents":        ("omarchy.agents",        PANEL_STYLE),
    "barista.audio":         ("omarchy.audio",         PANEL_STYLE),
    "barista.bluetooth":     ("omarchy.bluetooth",     PANEL_STYLE),
    "barista.clock":         ("omarchy.clock",         PANEL_STYLE),
    "barista.dropbox":       ("omarchy.dropbox",       PANEL_STYLE),
    "barista.monitor":       ("omarchy.monitor",       PANEL_STYLE),
    "barista.network":       ("omarchy.network",       PANEL_STYLE),
    "barista.power":         ("omarchy.power",         PANEL_STYLE),
    "barista.tailscale":     ("omarchy.tailscale",     PANEL_STYLE),
    "barista.clipboard":     ("omarchy.clipboard",     ["card-shadow"]),
    "barista.emojis":        ("omarchy.emojis",        ["card-shadow"]),
    "barista.polkit":        ("omarchy.polkit",        ["card-shadow"]),
    "barista.osd":           ("omarchy.osd",           ["card-shadow", "osd-gaps"]),
    "barista.notifications": ("omarchy.notifications", ["notify-gaps", "notify-shadow"]),
    "marcus.nightlight":     ("omarchy.nightlight",    ["nightlight-3000"]),
}

# Runtime sentence-casing. 4.5 moved the ALL-CAPS section labels into the
# shared i18n table (default/i18n/en/shell.json), which a clone can't edit,
# so the clone wraps those lookups instead. Only strings that are entirely
# upper-case change; translations in normal case pass through untouched.
CASE_JS = """.pragma library
// Generated by barista setup (plugin-clones). Sentence-cases ALL-CAPS labels
// from the shell's i18n table; anything not fully upper-case is returned as-is.
var KEEP = ["DNS", "VPN", "IP", "IPV4", "IPV6", "MAC", "SSID", "CPU", "GPU", "RAM", "USB",
            "HDMI", "LAN", "WAN", "UTC", "AM", "PM", "AI", "API", "ID", "HDR", "VRR",
            "FPS", "DPI", "DHCP", "GPT", "USD", "EUR", "GBP"]
var SPECIAL = { "WI-FI": "Wi-Fi" }

function sentence(value) {
  var s = String(value === undefined || value === null ? "" : value)
  if (s !== s.toUpperCase() || !/[A-Z]{2}/.test(s)) return s
  var first = true
  return s.split(" ").map(function(w) {
    var core = w.replace(/[^A-Z0-9-]/g, "")
    var out
    if (SPECIAL[core]) out = w.replace(core, SPECIAL[core])
    else if (KEEP.indexOf(core) >= 0 || /[0-9]/.test(w) || w.indexOf("%") >= 0) out = w
    else if (first) out = w.charAt(0) + w.slice(1).toLowerCase()
    else out = w.toLowerCase()
    if (/[A-Za-z]/.test(w)) first = false
    return out
  }).join(" ")
}
"""

JS_HELPER = """
// barista: sentence-case ALL-CAPS labels (generated; see BaristaCase.js).
function baristaSentence(value) {
  var s = String(value === undefined || value === null ? "" : value)
  if (s !== s.toUpperCase() || !/[A-Z]{2}/.test(s)) return s
  var keep = ["DNS", "VPN", "IP", "MAC", "SSID", "DHCP"]
  var first = true
  return s.split(" ").map(function(w) {
    var core = w.replace(/[^A-Z0-9-]/g, "")
    var out
    if (core === "WI-FI") out = w.replace(core, "Wi-Fi")
    else if (keep.indexOf(core) >= 0 || /[0-9]/.test(w) || w.indexOf("%") >= 0) out = w
    else if (first) out = w.charAt(0) + w.slice(1).toLowerCase()
    else out = w.toLowerCase()
    if (/[A-Za-z]/.test(w)) first = false
    return out
  }).join(" ")
}
"""


def caps_keys():
    """i18n keys whose English text is ALL CAPS (the labels to sentence-case)."""
    f = SHELL.parent / "default/i18n/en/shell.json"
    try:
        data = json.loads(f.read_text())
    except Exception:
        return set()
    out = set()
    def walk(o, p):
        if isinstance(o, dict):
            for k, v in o.items():
                walk(v, f"{p}.{k}" if p else k)
        elif isinstance(o, str) and o == o.upper() and len(re.findall(r"[A-Z]", o)) >= 3:
            out.add(p)
    walk(data, "")
    return out


class RuleMiss(Exception):
    pass


def log(msg):
    print(f"plugin-clones: {msg}")


# ------------------------------------------------------------------ rules
def rule_tnum(path, src):
    if path.suffix != ".qml":
        return src
    lines = src.splitlines(keepends=True)
    out = []
    for i, ln in enumerate(lines):
        out.append(ln)
        m = re.match(r"^(\s*)font\.family:", ln)
        if not m:
            continue
        # Skip if this font block already sets features (stock or re-run).
        window = "".join(lines[max(0, i - 4):i + 6])
        if "font.features" in window:
            continue
        out.append(f'{m.group(1)}font.features: {{ "tnum": 1 }}\n')
    return "".join(out)


def wrap_calls(src, pattern, keys, wrapper):
    """Wrap every call matching `pattern` (whose 1st group is an i18n key in
    `keys`) as wrapper(<call>). Balanced-paren scan; idempotent."""
    out, i = [], 0
    for m in re.finditer(pattern, src):
        if m.start() < i or m.group(1) not in keys:
            continue
        if src[max(0, m.start() - len(wrapper) - 1):m.start()] == wrapper + "(":
            continue
        # The match ends just past the key's closing quote; the call's "(" sits
        # right after the function name.
        j = src.index("(", m.start())
        depth, quote = 0, None
        while j < len(src):
            c = src[j]
            if quote:
                if c == "\\":
                    j += 1
                elif c == quote:
                    quote = None
            elif c in "\"'":
                quote = c
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            elif c == "\n":
                break                       # single-line calls only
            j += 1
        if depth != 0:
            continue
        out.append(src[i:m.start()] + wrapper + "(" + src[m.start():j + 1] + ")")
        i = j + 1
    out.append(src[i:])
    return "".join(out)


KEYS = None


def rule_sentence(path, src):
    global KEYS
    if KEYS is None:
        KEYS = caps_keys()
    if path.suffix == ".qml":
        new = wrap_calls(src, r'(?:Commons\.)?I18n\.t\(\s*"([\w.]+)"', KEYS, "BaristaCase.sentence")
        if new != src and 'as BaristaCase' not in new:
            rel = "../" * (len(path.parts) - 1) + "BaristaCase.js"
            lines = new.splitlines(keepends=True)
            last = max(i for i, l in enumerate(lines) if l.startswith("import "))
            lines.insert(last + 1, f'import "{rel}" as BaristaCase\n')
            new = "".join(lines)
        src = new
    elif path.suffix == ".js" and path.name != "BaristaCase.js":
        new = wrap_calls(src, r'(?<![\w.])t\(\s*"([\w.]+)"', KEYS, "baristaSentence")
        if new != src and "function baristaSentence" not in new:
            new = new.rstrip("\n") + "\n" + JS_HELPER
        src = new
    else:
        return src
    out = []
    for ln in src.splitlines(keepends=True):
        code = ln.split("//", 1)[0]
        # Caps produced in code (status phrases, month/day names): drop the
        # upper-casing on display bindings only — never charAt(0) capitalizers,
        # comparisons, or anything feeding a key/code.
        if ("toUpperCase()" in code and re.search(r"\btext:|\breturn\b", code)
                and "charAt(" not in code and "===" not in code and ".replace(" not in code):
            ln = ln.replace(".toUpperCase()", "")
        # ...including a multi-line binding closed by a bare `).toUpperCase()`.
        elif re.match(r"^\s*\)\.toUpperCase\(\)\s*$", code):
            ln = ln.replace(".toUpperCase()", "")
        # Caps labels carry tracking; sentence case doesn't want it.
        if re.match(r"^\s*font\.letterSpacing:\s*1(\.2)?\s*$", ln):
            continue
        out.append(ln)
    return "".join(out)


def shadow_supported():
    """BorderSurface only has `shadow` once step 10 patched it. Setting a
    non-existent property makes the whole clone fail to load — far worse
    than a flat card — so shadow rules are skipped until step 10 is in."""
    try:
        return "property bool shadow" in (SHELL / "Ui/BorderSurface.qml").read_text()
    except OSError:
        return False


def rule_card_shadow(path, src):
    if path.suffix != ".qml" or not shadow_supported():
        return src
    lines = src.splitlines(keepends=True)
    for i, ln in enumerate(lines):
        if ln.strip() == "id: card":
            if "shadow" in "".join(lines[i + 1:i + 6]):
                return src
            ind = ln[:len(ln) - len(ln.lstrip())]
            lines.insert(i + 1, f"{ind}shadow: true\n")
            return "".join(lines)
    return src


# Fallbacks keep the OSD/toasts at stock spacing if step 10's Style.qml
# hunk is gone (package update): undefined ?? gapsOut, never NaN -> 0px.
OSD_MARGIN = ("anchors.bottomMargin: Style.space(67) + (Style.shadowMargin || 0)"
              " + ((Style.gapBottom ?? Style.gapsOut) - Style.gapsOut)  // barista: per-side edge margins")


def rule_osd_gaps(path, src):
    if path.name != "Osd.qml":
        return src
    new, n = re.subn(r"anchors\.bottomMargin: Style\.space\(67\)[^\n]*", OSD_MARGIN, src, count=1)
    if n == 0:
        raise RuleMiss("Osd.qml: bottomMargin anchor not found")
    return new


def rule_notify_gaps(path, src):
    if path.name == "Delivery.js":
        old = ("function deckMargins(barPosition, thickness, gap) {\n"
               "  var position = String(barPosition || \"top\")\n"
               "  var edge = Number(gap)\n"
               "  if (!isFinite(edge)) edge = 0\n")
        new = ("// barista: per-side edge margins. topGap/rightGap are the halves of the\n"
               "// touched screen edges (Style.gapTop/gapRight from step 10); missing or\n"
               "// non-numeric they fall back to the scalar gap, so stock spacing holds.\n"
               "function deckMargins(barPosition, thickness, gap, topGap, rightGap) {\n"
               "  var position = String(barPosition || \"top\")\n"
               "  var edge = Number(gap)\n"
               "  if (!isFinite(edge)) edge = 0\n"
               "  var topEdge = isFinite(Number(topGap)) && topGap !== null && topGap !== undefined ? Number(topGap) : edge\n"
               "  var rightEdge = isFinite(Number(rightGap)) && rightGap !== null && rightGap !== undefined ? Number(rightGap) : edge\n")
        if "barista: per-side edge margins" in src:
            return src
        if old not in src:
            raise RuleMiss("Delivery.js: deckMargins signature changed")
        src = src.replace(old, new, 1)
        body_old = ("    top: (position === \"top\" ? bar : 0) + edge,\n"
                    "    right: (position === \"right\" ? bar : 0) + edge\n")
        body_new = ("    top: (position === \"top\" ? bar : 0) + topEdge,\n"
                    "    right: (position === \"right\" ? bar : 0) + rightEdge\n")
        if body_old not in src:
            raise RuleMiss("Delivery.js: deckMargins body changed")
        return src.replace(body_old, body_new, 1)
    if path.name == "Service.qml":
        old = "Delivery.barThickness(barRef, screenName, defaultBarSize), Style.gapsOut)"
        new = "Delivery.barThickness(barRef, screenName, defaultBarSize), Style.gapsOut, Style.gapTop, Style.gapRight)"
        if new in src:
            return src
        if old not in src:
            raise RuleMiss("Service.qml: marginsFor call changed")
        return src.replace(old, new, 1)
    return src


def rule_notify_shadow(path, src):
    if not shadow_supported():
        return src
    if path.name == "Toast.qml":
        old = "  BorderSurface {\n    id: plate\n"
        if old + "    shadow: true\n" in src:
            return src
        if old not in src:
            raise RuleMiss("Toast.qml: plate surface not found")
        return src.replace(old, old + "    shadow: true\n", 1)
    if path.name == "Service.qml":
        if "barista: shadow room" in src:
            return src
        # The deck clipper exists for the arrival animation; give it room for
        # the card shadow on the left/top/bottom without moving the cards.
        reps = [
            ("        anchors.topMargin: surface.margins.top\n"
             "        // Room for the arrival's scale animation, and the gap from the edge.\n"
             "        readonly property int motionInset: Style.spacing.sm\n",
             "        anchors.topMargin: surface.margins.top - topRoom\n"
             "        // Room for the arrival's scale animation, and the gap from the edge.\n"
             "        // barista: shadow room — inset grows to the card shadow so the\n"
             "        // clip doesn't slice it; topRoom shifts the deck back down so the\n"
             "        // cards land exactly where stock puts them.\n"
             "        readonly property int motionInset: Math.max(Style.spacing.sm, Style.shadowMargin || 0)\n"
             "        readonly property int topRoom: Math.min(motionInset, surface.margins.top)\n"),
            ("          x: clipper.motionInset\n          width: service.notificationWidth\n",
             "          x: clipper.motionInset\n          y: clipper.topRoom\n          width: service.notificationWidth\n"),
        ]
        for o, n in reps:
            if o not in src:
                raise RuleMiss("Service.qml: deck clipper layout changed")
            src = src.replace(o, n, 1)
        return src
    return src


def rule_nightlight_3000(path, src):
    if path.name != "Service.qml":
        return src
    new, n = re.subn(r"readonly property int nightTemperature: \d+",
                     "readonly property int nightTemperature: 3000  // barista: matches ~/.local/bin/omarchy-toggle-nightlight", src, count=1)
    if n == 0:
        raise RuleMiss("nightlight: nightTemperature not found")
    return new


RULES = {
    "tnum": rule_tnum, "sentence": rule_sentence, "card-shadow": rule_card_shadow,
    "osd-gaps": rule_osd_gaps, "notify-gaps": rule_notify_gaps,
    "notify-shadow": rule_notify_shadow, "nightlight-3000": rule_nightlight_3000,
}


# ------------------------------------------------------------------ build
def stock_dirs():
    out = {}
    root = SHELL / "plugins"
    for m in root.rglob("manifest.json"):
        try:
            out[json.loads(m.read_text())["id"]] = m.parent
        except Exception:
            pass
    return out


def build(clone_id, stock_dir, rules, dest):
    """Copy stock_dir -> dest, apply rules, write clone manifest."""
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(stock_dir, dest, symlinks=False,
                    ignore=shutil.ignore_patterns("*.bak-*", "*.bak"))
    # Folders that only held step-10 backups upstream come over empty.
    for d in sorted((p for p in dest.rglob("*") if p.is_dir()), reverse=True):
        if not any(d.iterdir()):
            d.rmdir()
    if "sentence" in rules:
        (dest / "BaristaCase.js").write_text(CASE_JS)
    for f in sorted(dest.rglob("*")):
        if not f.is_file() or f.suffix not in (".qml", ".js"):
            continue
        src = orig = f.read_text()
        for r in rules:
            src = RULES[r](f.relative_to(dest), src)
        if src != orig:
            f.write_text(src)
    # Manifest: upstream's (new fields included), re-identified as the clone
    # exactly the way omarchy-plugin-clone does it.
    man = json.loads((stock_dir / "manifest.json").read_text())
    source_id = man["id"]
    old_man = {}
    if (PLUGINS / clone_id / "manifest.json").exists():
        old_man = json.loads((PLUGINS / clone_id / "manifest.json").read_text())
    man["id"] = clone_id
    man["name"] = old_man.get("name") or ("Barista " + man.get("name", clone_id))
    if isinstance(man.get("barWidget"), dict):
        man["barWidget"]["displayName"] = man["name"]
    om = man.get("omarchy") if isinstance(man.get("omarchy"), dict) else {}
    om.pop("clonePaths", None)
    om["clonedFrom"] = source_id
    om["baristaGenerated"] = True
    man["omarchy"] = om
    (dest / "manifest.json").write_text(json.dumps(man, indent=2) + "\n")


def selected(only):
    ids = list(MANAGED)
    if only:
        want = set(only.split(","))
        ids = [i for i in ids if i in want]
    return ids


def cmd_apply(only, check=False):
    stock = stock_dirs()
    if not shadow_supported():
        log("BorderSurface has no shadow support (step 10 not applied) — cards stay flat")
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    bdir = BACKUPS / stamp
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="barista-clones."))
    failed = []
    try:
        for cid in selected(only):
            sid, rules = MANAGED[cid]
            live = PLUGINS / cid
            if not live.exists():
                log(f"skip {cid}: not installed")
                continue
            if sid not in stock:
                log(f"skip {cid}: stock {sid} not found in {SHELL}")
                continue
            staged = tmp / cid
            try:
                build(cid, stock[sid], rules, staged)
            except RuleMiss as e:
                log(f"FAIL {cid}: {e} (left untouched)")
                failed.append(cid)
                continue
            diff = subprocess.run(["diff", "-rq", str(live), str(staged)],
                                  capture_output=True, text=True).stdout.strip()
            if not diff:
                log(f"ok   {cid}: up to date")
                continue
            if check:
                log(f"diff {cid}: {len(diff.splitlines())} file(s) would change")
                continue
            bdir.mkdir(parents=True, exist_ok=True)
            shutil.move(str(live), str(bdir / cid))
            shutil.move(str(staged), str(live))
            log(f"regen {cid} (from {sid}; previous copy in {bdir / cid})")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    # Keep the five most recent backup sets; older ones are superseded.
    if BACKUPS.exists() and not check:
        sets = sorted(p for p in BACKUPS.iterdir() if p.is_dir() and p.name[:8].isdigit())
        for old in sets[:-5]:
            shutil.rmtree(old, ignore_errors=True)
    if failed:
        log("some clones need a rule update for this omarchy version: " + ", ".join(failed))
        return 1
    return 0


def cmd_revert(only):
    if not BACKUPS.exists() or not any(BACKUPS.iterdir()):
        log("nothing to revert")
        return 0
    last = sorted(p for p in BACKUPS.iterdir() if p.is_dir())[-1]
    for saved in sorted(last.iterdir()):
        if only and saved.name not in only.split(","):
            continue
        live = PLUGINS / saved.name
        if live.exists():
            shutil.rmtree(live)
        shutil.move(str(saved), str(live))
        log(f"restored {saved.name} from {last}")
    if not any(last.iterdir()):
        last.rmdir()
    return 0


def main():
    global PLUGINS
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["apply", "revert", "check"])
    ap.add_argument("--plugins-dir")
    ap.add_argument("--only")
    a = ap.parse_args()
    if a.plugins_dir:
        PLUGINS = pathlib.Path(a.plugins_dir)
    if a.mode == "revert":
        return cmd_revert(a.only)
    return cmd_apply(a.only, check=(a.mode == "check"))


if __name__ == "__main__":
    sys.exit(main())
